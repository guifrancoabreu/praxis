#!/usr/bin/env python3
"""Keep the shared design tokens honest across platforms.

`design/tokens.json` is the source of truth. This script
  * verifies that `ios/Praxis/RefTokens.swift` still carries the same values, and
  * generates `android/.../design/Tokens.kt` when the Android app exists.

Usage:
  python3 tools/gen_tokens.py --check   # verify only (CI)
  python3 tools/gen_tokens.py --write   # verify, then rewrite the Kotlin tokens
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
SWIFT = ROOT / "ios" / "Praxis" / "RefTokens.swift"
KOTLIN = ROOT / "android" / "app" / "src" / "main" / "kotlin" / "br" / "praxis" / "android" / "design" / "Tokens.kt"

# Swift enum name -> token group. Numbers and hex strings are read the same way.
GROUPS = {
    "Spacing": "spacing",
    "Radius": "radius",
    "Sizing": "sizing",
    "Colors": "colors",
    "Opacity": "opacity",
    "Shadow": "shadow",
    "Typography": "typography",
}
NUMBER = re.compile(r"static let (\w+): CGFloat = (-?\d+(?:\.\d+)?)")
STRING = re.compile(r'static let (\w+) = "(#[0-9A-Fa-f]{6})"')


def load_tokens() -> dict:
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def swift_values(source: str) -> dict[str, dict[str, object]]:
    """Reads the flat values declared inside each RefTokens enum."""
    groups: dict[str, dict[str, object]] = {}
    for name, group in GROUPS.items():
        match = re.search(rf"enum {name} \{{(.*?)\n    \}}", source, re.DOTALL)
        if not match:
            continue
        body = match.group(1)
        values: dict[str, object] = {}
        for key, value in NUMBER.findall(body):
            values[key] = float(value) if "." in value else int(value)
        for key, value in STRING.findall(body):
            values[key] = value
        groups[group] = values
    return groups


def check() -> list[str]:
    tokens = load_tokens()
    swift = swift_values(SWIFT.read_text(encoding="utf-8"))
    errors: list[str] = []
    for group, expected in tokens.items():
        if group.startswith("$"):
            continue
        actual = swift.get(group, {})
        for key, value in expected.items():
            if key not in actual:
                errors.append(f"RefTokens is missing {group}.{key} ({value})")
            elif actual[key] != value:
                errors.append(f"RefTokens {group}.{key} is {actual[key]}, tokens.json says {value}")
        for key in actual:
            if key not in expected:
                errors.append(f"tokens.json is missing {group}.{key} (Swift has {actual[key]})")
    return errors


def kotlin(tokens: dict) -> str:
    lines = [
        "// Generated by tools/gen_tokens.py from design/tokens.json. Do not edit by hand.",
        "package br.praxis.android.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "object Tokens {",
    ]
    sections = [
        ("spacing", "Spacing", lambda k, v: f"val {_lower(k)} = {_num(v)}.dp"),
        ("radius", "Radius", lambda k, v: f"val {_lower(k)} = {_num(v)}.dp"),
        ("sizing", "Sizing", lambda k, v: f"val {_lower(k)} = {_num(v)}.dp"),
        ("opacity", "Opacity", lambda k, v: f"val {_lower(k)} = {_num(v)}f"),
    ]
    for group, name, render in sections:
        lines.append(f"    object {name} {{")
        for key, value in tokens[group].items():
            lines.append(f"        {render(key, value)}")
        lines.append("    }")
        lines.append("")
    lines += [
        "    object Shadow {",
        f"        val coverRadius = {_num(tokens['shadow']['coverRadius'])}.dp",
        f"        val coverOffsetY = {_num(tokens['shadow']['coverOffsetY'])}.dp",
        "    }",
        "",
        "    object Typography {",
    ]
    for key, value in tokens["typography"].items():
        lines.append(f"        val {_lower(key)} = {_num(value)}.sp")
    lines += ["    }", "", "    object Colors {"]
    for key, value in tokens["colors"].items():
        lines.append(f'        val {_lower(key)} = Color(0xFF{value.lstrip("#").upper()})')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def _lower(name: str) -> str:
    return re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), name)


def _num(value: object) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def main(argv: list[str]) -> int:
    errors = check()
    if errors:
        print("token check failed:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    if "--write" in argv:
        KOTLIN.parent.mkdir(parents=True, exist_ok=True)
        KOTLIN.write_text(kotlin(load_tokens()), encoding="utf-8")
        print(f"wrote {KOTLIN.relative_to(ROOT)}")
    print("tokens OK: design/tokens.json matches RefTokens.swift")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
