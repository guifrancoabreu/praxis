#!/usr/bin/env python3
"""Keep the shared design tokens honest across platforms.

`design/tokens.json` is the single source of truth. This script renders both
platform token files from it and compares them against what is on disk:
  * `ios/Praxis/RefTokens.swift`
  * `android/.../design/Tokens.kt`

Usage:
  python3 tools/gen_tokens.py --check   # verify only (CI)
  python3 tools/gen_tokens.py --write   # regenerate both token files
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
SWIFT = ROOT / "ios" / "Praxis" / "RefTokens.swift"
KOTLIN = ROOT / "android" / "app" / "src" / "main" / "kotlin" / "br" / "praxis" / "android" / "design" / "Tokens.kt"

HEADER = "// Generated by tools/gen_tokens.py from design/tokens.json. Do not edit by hand."

# Numeric token groups, in source order, with optional explanatory comments.
SWIFT_NUMERIC = [
    ("Spacing", "spacing", "// Monorepo reference scale; each step maps to 4 pt on iOS."),
    ("Radius", "radius", None),
    ("Sizing", "sizing", None),
]
SWIFT_TRAILING_NUMERIC = [
    ("Opacity", "opacity", None),
    ("Shadow", "shadow", None),
    ("Typography", "typography", "// Prefer native SwiftUI text styles in app UI; these sizes are for custom artwork only."),
]
KOTLIN_DP_GROUPS = [("Spacing", "spacing"), ("Radius", "radius"), ("Sizing", "sizing")]
KOTLIN_SCALAR_GROUPS = [("Opacity", "opacity", "f"), ("Typography", "typography", "sp")]


def load_tokens() -> dict:
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def _name(key: str) -> str:
    """Kebab-case and snake_case keys become camelCase identifiers."""
    words = key.replace("_", "-").split("-")
    return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:])


def _num(value: object) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def _indent(lines: list[str], spaces: int) -> list[str]:
    pad = " " * spaces
    return [f"{pad}{line}" if line else "" for line in lines]


def _swift_enum(name: str, entries: list[str], indent: int = 4) -> list[str]:
    pad = " " * indent
    lines = [f"{pad}enum {name} {{"]
    lines += [f"{pad}    {entry}" if entry else "" for entry in entries]
    lines.append(f"{pad}}}")
    return lines


def render_swift(tokens: dict) -> str:
    groups: list[list[str]] = []
    for enum, group, comment in SWIFT_NUMERIC:
        entries = [f"static let {key}: CGFloat = {_num(value)}" for key, value in tokens[group].items()]
        body = _swift_enum(enum, ([comment] if comment else []) + entries)
        groups.append(body)
    groups.append(_swift_enum("Colors", [f'static let {key} = "{value}"' for key, value in tokens["colors"].items()]))
    for enum, group, comment in SWIFT_TRAILING_NUMERIC:
        entries = [f"static let {key}: CGFloat = {_num(value)}" for key, value in tokens[group].items()]
        body = _swift_enum(enum, ([comment] if comment else []) + entries)
        groups.append(body)
    groups.append(_swift_enum("Semantic", _swift_semantic(tokens)))
    groups.append(_swift_enum("TypeScale", _swift_type_scale(tokens)))
    groups.append(_swift_enum("Reader", _swift_reader(tokens)))

    lines = [HEADER, "", "import Foundation", "", "/// Primitive values shared across themes and components.", "enum RefTokens {"]
    for index, body in enumerate(groups):
        if index:
            lines.append("")
        lines += body
    lines += ["}", ""]
    return "\n".join(lines)


def _swift_semantic(tokens: dict) -> list[str]:
    entries = []
    for key, pair in tokens["semantic"].items():
        name = _name(key)
        entries.append(f'static let {name}Light = "{pair["light"]}"')
        entries.append(f'static let {name}Dark = "{pair["dark"]}"')
    return entries


def _swift_type_scale(tokens: dict) -> list[str]:
    entries = []
    for key, value in tokens["type-scale"].items():
        name = _name(key)
        entries += [
            f"static let {name}Size: CGFloat = {_num(value['size'])}",
            f"static let {name}Leading: CGFloat = {_num(value['leading'])}",
            f'static let {name}Weight = "{value["weight"]}"',
            f'static let {name}Family = "{value["family"]}"',
        ]
    return entries


def _swift_reader(tokens: dict) -> list[str]:
    entries: list[str] = []
    for index, (theme, palette) in enumerate(tokens["reader"].items()):
        if index:
            entries.append("")
        entries += _swift_enum(theme.title(), [f'static let {role} = "{value}"' for role, value in palette.items()], indent=0)
    return entries


def render_kotlin(tokens: dict) -> str:
    blocks: list[list[str]] = []
    for name, group in KOTLIN_DP_GROUPS:
        blocks.append(_kotlin_object(name, [f"val {_name(key)} = {_num(value)}.dp" for key, value in tokens[group].items()]))
    for name, group, unit in KOTLIN_SCALAR_GROUPS:
        blocks.append(_kotlin_object(name, [f"val {_name(key)} = {_kotlin_number(value, unit)}" for key, value in tokens[group].items()]))
    blocks.append(_kotlin_object("Shadow", [f"val {key} = {_num(value)}.dp" for key, value in tokens["shadow"].items()]))
    blocks.append(
        _kotlin_object("Colors", [f"val {_name(key)} = {_kotlin_color(value)}" for key, value in tokens["colors"].items()])
    )
    blocks.append(_kotlin_object("Semantic", _kotlin_semantic(tokens)))
    blocks.append(_kotlin_object("TypeScale", _kotlin_type_scale(tokens)))
    blocks.append(_kotlin_object("Reader", _kotlin_reader(tokens)))

    lines = [
        HEADER,
        "package br.praxis.android.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "object Tokens {",
    ]
    for index, block in enumerate(blocks):
        if index:
            lines.append("")
        lines += _indent(block, 4)
    lines += ["}", ""]
    return "\n".join(lines)


def _kotlin_object(name: str, entries: list[str]) -> list[str]:
    return [f"object {name} {{", *[f"    {entry}" if entry else "" for entry in entries], "}"]


def _kotlin_number(value: object, unit: str) -> str:
    # Compose's float suffix sits tight against the number (`0.45f`); dp/sp need a dot.
    return f"{_num(value)}f" if unit == "f" else f"{_num(value)}.{unit}"


def _kotlin_color(value: str) -> str:
    # 6-digit hex becomes #FFRRGGBB; 8-digit AARRGGBB already carries its alpha.
    hex_value = value.lstrip("#").upper()
    return f"Color(0x{hex_value if len(hex_value) == 8 else 'FF' + hex_value})"


def _kotlin_semantic(tokens: dict) -> list[str]:
    entries = []
    for key, pair in tokens["semantic"].items():
        name = _name(key)
        entries.append(f"val {name}Light = {_kotlin_color(pair['light'])}")
        entries.append(f"val {name}Dark = {_kotlin_color(pair['dark'])}")
    return entries


def _kotlin_type_scale(tokens: dict) -> list[str]:
    entries = []
    for key, value in tokens["type-scale"].items():
        name = _name(key)
        entries += [
            f"val {name}Size = {_num(value['size'])}.sp",
            f"val {name}Leading = {_num(value['leading'])}.sp",
            f'val {name}Weight = "{value["weight"]}"',
            f'val {name}Family = "{value["family"]}"',
        ]
    return entries


def _kotlin_reader(tokens: dict) -> list[str]:
    entries: list[str] = []
    for index, (theme, palette) in enumerate(tokens["reader"].items()):
        if index:
            entries.append("")
        entries += _kotlin_object(theme.title(), [f"val {role} = {_kotlin_color(value)}" for role, value in palette.items()])
    return entries


RENDERERS = ((SWIFT, render_swift), (KOTLIN, render_kotlin))


def check() -> list[str]:
    tokens = load_tokens()
    errors: list[str] = []
    for path, render in RENDERERS:
        name = path.relative_to(ROOT)
        if not path.exists():
            errors.append(f"{name} is missing; run python3 tools/gen_tokens.py --write to generate it")
        elif path.read_text(encoding="utf-8") != render(tokens):
            errors.append(f"{name} is stale; run python3 tools/gen_tokens.py --write to regenerate it")
    return errors


def main(argv: list[str]) -> int:
    tokens = load_tokens()
    if "--write" in argv:
        for path, render in RENDERERS:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render(tokens), encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    errors = check()
    if errors:
        print("token check failed:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    print("tokens OK: design/tokens.json matches RefTokens.swift and Tokens.kt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
