#!/usr/bin/env python3
"""Generate the platform icon assets from the Lucide masters in `shared/assets/icons/`.

Lucide ships plain SVGs on a 24×24 grid, stroke-based, with no official Swift or Compose
package. Both apps therefore get generated assets from the same master:

  * iOS: an `.imageset` holding the SVG, marked template-rendering so SwiftUI tints it.
  * Android: a vector drawable. Vector drawables cannot hold `circle`, `rect`, `line`,
    `polyline` or `polygon` elements, so every shape is reduced to `pathData` here.

Usage:
  python3 tools/sync_icons.py --check   # verify the generated assets (CI)
  python3 tools/sync_icons.py --write   # regenerate them
"""

from __future__ import annotations

import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
MASTERS = ROOT / "shared" / "assets" / "icons"
IOS_CATALOG = ROOT / "ios" / "Praxis" / "Assets.xcassets"
ANDROID_DRAWABLE = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"

STROKE = "#FF000000"
CLEAR = "#00000000"
CONTENTS = """{
  "images" : [
    {
      "filename" : "icon.svg",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "preserves-vector-representation" : true,
    "template-rendering-intent" : "template"
  }
}
"""


def icon_names() -> list[str]:
    return sorted(path.stem for path in MASTERS.glob("*.svg"))


def camel(name: str) -> str:
    return re.sub(r"-([a-z0-9])", lambda match: match.group(1).upper(), name)


def snake(name: str) -> str:
    return name.replace("-", "_")


def num(element: ET.Element, key: str, default: float = 0.0) -> float:
    return float(element.get(key, default))


# --- shape to pathData -------------------------------------------------------


def circle_path(cx: float, cy: float, r: float) -> str:
    return (
        f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0"
    )


def rect_path(x: float, y: float, width: float, height: float, rx: float) -> str:
    if rx <= 0:
        return f"M{x},{y} h{width} v{height} h{-width} Z"
    r = min(rx, width / 2, height / 2)
    return (
        f"M{x + r},{y} h{width - 2 * r} a{r},{r} 0 0,1 {r},{r} "
        f"v{height - 2 * r} a{r},{r} 0 0,1 {-r},{r} "
        f"h{-(width - 2 * r)} a{r},{r} 0 0,1 {-r},{-r} "
        f"v{-(height - 2 * r)} a{r},{r} 0 0,1 {r},{-r} Z"
    )


def points_path(raw: str, close: bool) -> str:
    pairs = raw.replace(",", " ").split()
    coords = [(pairs[i], pairs[i + 1]) for i in range(0, len(pairs) - 1, 2)]
    if not coords:
        return ""
    head = "M" + ",".join(coords[0])
    tail = "".join(" L" + ",".join(pair) for pair in coords[1:])
    return head + tail + (" Z" if close else "")


def path_data(element: ET.Element) -> str:
    tag = element.tag.split("}")[-1]
    if tag == "path":
        return element.get("d", "")
    if tag == "circle":
        return circle_path(num(element, "cx"), num(element, "cy"), num(element, "r"))
    if tag == "rect":
        return rect_path(
            num(element, "x"),
            num(element, "y"),
            num(element, "width"),
            num(element, "height"),
            num(element, "rx", num(element, "ry")),
        )
    if tag == "line":
        return (
            f"M{num(element, 'x1')},{num(element, 'y1')} "
            f"L{num(element, 'x2')},{num(element, 'y2')}"
        )
    if tag == "polyline":
        return points_path(element.get("points", ""), close=False)
    if tag == "polygon":
        return points_path(element.get("points", ""), close=True)
    return ""


def fmt(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else str(value)


def vector_drawable(svg_path: pathlib.Path) -> str:
    root = ET.parse(svg_path).getroot()
    width = fmt(float(root.get("width", "24")))
    height = fmt(float(root.get("height", "24")))
    view = root.get("viewBox", f"0 0 {width} {height}").split()

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/sync_icons.py from shared/assets/icons. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width}dp"',
        f'    android:height="{height}dp"',
        f'    android:viewportWidth="{view[2]}"',
        f'    android:viewportHeight="{view[3]}">',
    ]
    inherited_stroke = root.get("stroke", "none") != "none"
    stroke_width = root.get("stroke-width", "2")
    line_cap = root.get("stroke-linecap", "round")
    line_join = root.get("stroke-linejoin", "round")
    cap_map = {"round": "round", "butt": "butt", "square": "square"}
    join_map = {"round": "round", "miter": "miter", "bevel": "bevel"}

    for element in root:
        data = path_data(element)
        if not data:
            continue
        attributes = [f'        android:pathData="{data}"']
        stroke = element.get("stroke", "currentColor" if inherited_stroke else "none")
        fill = element.get("fill", "none")
        if stroke != "none":
            attributes.append(f'        android:strokeColor="{STROKE}"')
            attributes.append(
                f'        android:strokeWidth="{element.get("stroke-width", stroke_width)}"'
            )
            attributes.append(
                f'        android:strokeLineCap="{cap_map.get(element.get("stroke-linecap", line_cap), "round")}"'
            )
            attributes.append(
                f'        android:strokeLineJoin="{join_map.get(element.get("stroke-linejoin", line_join), "round")}"'
            )
        attributes.append(
            f'        android:fillColor="{STROKE if fill not in ("none", "") else CLEAR}"'
        )
        lines.append("    <path")
        lines.extend(attributes)
        lines.append("    />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def template_svg(svg_path: pathlib.Path) -> str:
    """The SVG as the app should ship it: an explicit black stroke, no CSS keyword, so template tinting is predictable."""
    text = svg_path.read_text(encoding="utf-8")
    return text.replace('stroke="currentColor"', 'stroke="#000000"')


def generated() -> dict[pathlib.Path, str]:
    files: dict[pathlib.Path, str] = {}
    for name in icon_names():
        master = MASTERS / f"{name}.svg"
        imageset = IOS_CATALOG / f"lucide-{name}.imageset"
        files[imageset / "icon.svg"] = template_svg(master)
        files[imageset / "Contents.json"] = CONTENTS
        files[ANDROID_DRAWABLE / f"lucide_{snake(name)}.xml"] = vector_drawable(master)
    return files


def check() -> list[str]:
    problems: list[str] = []
    expected = generated()
    for path, text in expected.items():
        if not path.is_file():
            problems.append(f"{path.relative_to(ROOT)} is missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{path.relative_to(ROOT)} is out of date")
    expected_paths = set(expected)
    for path in sorted(IOS_CATALOG.glob("lucide-*.imageset")):
        if path / "icon.svg" not in expected_paths:
            problems.append(f"{path.relative_to(ROOT)} has no master in shared/assets/icons")
    for path in sorted(ANDROID_DRAWABLE.glob("lucide_*.xml")):
        if path not in expected_paths:
            problems.append(f"{path.relative_to(ROOT)} has no master in shared/assets/icons")
    return problems


def write() -> None:
    expected = generated()
    for path, text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    # A master that was removed or renamed should not leave a generated asset behind.
    for directory in IOS_CATALOG.glob("lucide-*.imageset"):
        if directory / "icon.svg" not in expected:
            for leftover in directory.iterdir():
                leftover.unlink()
            directory.rmdir()
    for leftover in ANDROID_DRAWABLE.glob("lucide_*.xml"):
        if leftover not in expected:
            leftover.unlink()
    print(f"wrote icons for {len(icon_names())} masters: {', '.join(icon_names())}")


def main(argv: list[str]) -> int:
    if not MASTERS.is_dir():
        print(f"missing master directory: {MASTERS.relative_to(ROOT)}", file=sys.stderr)
        return 1
    if "--write" in argv:
        write()
    problems = check()
    if problems:
        print("icon check failed:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print("run python3 tools/sync_icons.py --write", file=sys.stderr)
        return 1
    print(f"icons OK: {len(icon_names())} masters match every platform")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
